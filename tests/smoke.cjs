const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const baseURL = process.env.JOSTER_TEST_URL || 'http://127.0.0.1:4173/';
const fixture = name => path.join(process.env.JOSTER_TEST_DIR || '/tmp/joster-fixtures', name);
(async () => {
 const browser = await chromium.launch({executablePath:process.env.CHROMIUM_EXECUTABLE || '/usr/bin/chromium',args:['--no-sandbox','--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
 try {
 const context=await browser.newContext({acceptDownloads:true,permissions:['microphone']});
 const page=await context.newPage(), errors=[];
 page.setDefaultTimeout(12000);
 page.on('pageerror',e=>{errors.push(e.message);console.error(e.message)});
 page.on('dialog',d=>d.accept());
 await page.goto(baseURL);
 await page.waitForFunction(()=>document.querySelector('#recoveryStatus').textContent.includes('media available'));
 await page.locator('#mediaInput').setInputFiles(fixture('sync.mp4'));
 await page.waitForFunction(()=>document.querySelector('.media-item small')?.textContent.includes('00:02.0'));
 await page.getByRole('button',{name:/sync.mp4/}).click();
 await page.locator('#addSelectedBtn').click();
 await page.getByLabel('Speed',{exact:true}).selectOption('0.5');
 assert.equal(await page.locator('#durationLabel').textContent(),'4.0 seconds');
 await page.getByLabel('Speed',{exact:true}).selectOption('1');
 await page.getByLabel('Reverse video (silent)').check();
 await page.locator('#navSeek').evaluate(e=>{e.value=1;e.dispatchEvent(new Event('input'))});
 await page.locator('#splitBtn').click();
 assert.equal(await page.locator('.clip.video').count(),2);
 await page.locator('#undoBtn').click();
 assert.equal(await page.locator('.clip.video').count(),1);
 await page.locator('.clip.video').click();
 await page.getByLabel('Reverse video (silent)').uncheck();
 await page.getByLabel('Bass (dB)').fill('2');
 await page.getByLabel('Bass (dB)').press('Tab');
 await page.getByLabel('Noise gate',{exact:true}).check();
 await page.locator('#saveBtn').click();
 await page.waitForFunction(()=>document.querySelector('#saveStatus').textContent==='Saved locally');
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('#recoveryStatus').textContent.includes('1 media available'));
 assert.equal(await page.locator('.clip.video').count(),1);
 await page.waitForFunction(async()=>!!(await navigator.serviceWorker.getRegistration())?.active);
 await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
 await context.setOffline(true);
 await page.reload();
 await page.waitForFunction(()=>document.querySelector('#recoveryStatus').textContent.includes('1 media available'));
 await context.setOffline(false);
 let result=page.waitForEvent('download');
 await page.getByRole('button',{name:'Back up with media'}).click();
 await (await result).saveAs(fixture('backup.joster'));
 const fresh=await browser.newContext();
 const freshPage=await fresh.newPage();
 await freshPage.goto(baseURL);
 await freshPage.waitForFunction(()=>document.querySelector('#recoveryStatus').textContent.includes('media available'));
 await freshPage.locator('#projectInput').setInputFiles(fixture('backup.joster'));
 await freshPage.waitForFunction(()=>document.querySelector('#recoveryStatus').textContent.includes('1 media available'));
 assert.equal(await freshPage.locator('.clip.video').count(),1);
 await fresh.close();
 await page.locator('#renderBtn').click();
 await page.locator('#renderResolution').selectOption('480');
 await page.locator('#renderFormat').selectOption('webm');
 result=page.waitForEvent('download');
 await page.locator('#startRender').click();
 await (await result).saveAs(fixture('export.webm'));
 await page.locator('#cancelRender').click();
 await page.locator('#renderBtn').click();
 await page.locator('#renderFormat').selectOption('mp4');
 await page.locator('#renderRatio').selectOption('portrait');
 result=page.waitForEvent('download');
 await page.locator('#startRender').click();
 const portrait=await result;
 await portrait.saveAs(fixture('portrait-'+portrait.suggestedFilename()));
 await page.locator('#cancelRender').click();
 await page.locator('#mediaInput').setInputFiles(fixture('tone.wav'));
 await page.getByRole('button',{name:/tone.wav/}).click();
 await page.locator('#addSelectedBtn').click();
 assert.equal(await page.locator('.clip.audio').count(),1);
 await page.getByLabel('Stereo pan',{exact:true}).fill('-25');
 await page.getByLabel('Stereo pan',{exact:true}).press('Tab');
 await page.locator('#voiceRecord').click();
 await page.waitForFunction(()=>document.querySelector('#voiceRecord').textContent==='Stop recording');
 await page.waitForTimeout(350);
 await page.locator('#voiceRecord').click();
 await page.waitForFunction(()=>document.querySelector('#voiceRecord').textContent==='Record voiceover');
 assert.equal(await page.locator('.clip.audio').count(),2);
 await page.locator('#thumbOpen').click();
 await page.locator('#thumbFrame').click();
 result=page.waitForEvent('download');
 await page.locator('#thumbSave').click();
 await (await result).saveAs(fixture('thumb.png'));
 await page.locator('#thumbClose').click();
 const mobile=await browser.newContext({viewport:{width:390,height:844},hasTouch:true,isMobile:true});
 const touch=await mobile.newPage();
 touch.on('pageerror',e=>errors.push(e.message));
 await touch.goto(baseURL);
 await touch.waitForFunction(()=>document.querySelector('#recoveryStatus').textContent.includes('media available'));
 await touch.locator('#mediaInput').setInputFiles(fixture('sync.mp4'));
 await touch.getByRole('button',{name:/sync.mp4/}).tap();
 await touch.locator('#addSelectedBtn').tap();
 assert.equal(await touch.locator('.clip.video').count(),1);
 await touch.locator('#mobileRatio').selectOption('square');
 assert.equal(await touch.locator('#layerPreview').evaluate(e=>e.width===e.height),true);
 assert.equal(await touch.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await mobile.close();
 assert.deepEqual(errors,[]);
 console.log('PASS import, retime, reverse split, undo, EQ, save/reload, offline reload, portable backup, WebM render, audio track, browser microphone, thumbnail, portrait export and touch-width square preview');
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exitCode=1});
